import { useEffect } from 'react';

/**
 * Прокрутка к разделу главной по якорю из адреса.
 *
 * React Router меняет адрес через History API, и нативный переход по якорю при
 * этом не срабатывает: с `/pricing` пользователь попадал на верх главной, хотя в
 * адресе стоял `#features`, и раздел открывался только после перезагрузки.
 * Раздел открывает сама страница-получатель, поэтому этого хватает любой ссылке с
 * базой `/` — и в шапке, и в подвале, и с публичной страницы документа.
 *
 * На самой главной якоря остаются обычными ссылками (`#features`), и прокрутку
 * делает браузер — там `scroll-behavior: smooth` из `index.css` уместен: раздел
 * рядом. После смены страницы всё иначе: человек пришёл на главную ради раздела,
 * и ждать анимацию через пол-экрана незачем — открываем раздел сразу.
 */
export function useHashScroll(hash: string): void {
  useEffect(() => {
    const id = hash.replace(/^#/, '');
    if (!id) return;
    document.getElementById(id)?.scrollIntoView({ behavior: 'instant' });
  }, [hash]);
}
