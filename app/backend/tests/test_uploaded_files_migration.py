"""Ревизия `0053_uploaded_files`: реестр загрузок и `import_jobs.file_key`.

DDL ревизии — `CREATE TABLE ... IF NOT EXISTS` и
`ALTER TABLE ... ADD COLUMN IF NOT EXISTS` — юнит-тестом на SQLite целиком не
выполнить: `ADD COLUMN IF NOT EXISTS` понимает PostgreSQL, а не SQLite, а
`DEFAULT now()` SQLite отвергает как непостоянное значение. Поэтому проверяются
три вещи, которые ломаются тихо:

* сама ревизия стоит на голове дерева, и голова одна (вторая голова валит
  `alembic upgrade head` с «Multiple head revisions»);
* объявление таблицы реестра совпадает с моделью `UploadedFile` по именам и
  типам колонок и объявляет те же индексы — расхождение всплывает только на
  живой базе как `UndefinedColumn`;
* колонка `import_jobs.file_key` добавлена nullable и без `DEFAULT` (backfill
  нет) и снимается в `downgrade` — иначе ревизия необратима.

Сам DDL на настоящей PostgreSQL проверяется на стенде: `alembic upgrade head`,
затем `alembic downgrade -1` и снова `alembic upgrade head`.
"""

import re
from pathlib import Path
from types import ModuleType

from app.models.import_job import ImportJob
from app.models.uploaded_file import UploadedFile
from tests.migration_support import (
    added_columns,
    assert_columns_match_model,
    assert_downgrade_removes_only_added,
    assert_nullable_without_default,
    assert_on_previous_head,
    assert_single_head,
    column_type_sql,
    load_migration,
    model_columns,
    type_matches,
)

ALEMBIC_DIR = Path(__file__).resolve().parents[1] / "alembic"
MIGRATION_PATH = ALEMBIC_DIR / "versions" / "0053_uploaded_files.py"
REVISION = "0053_uploaded_files"
PARENT = "0052_tariff_prices"

# Колонка задания импорта: ключ хранилища без префикса `uploads/`.
COLUMN_PREFIX = "file_"

# Объявление колонки в `CREATE TABLE`: имя и тип. Хвост ограничений
# (`DEFAULT ... NOT NULL`) намеренно не разбирается — его проверяет
# `test_created_table_matches_the_model` отдельно, по модели. Правая граница —
# пробел, запятая или скобка, а не `\b`: у `VARCHAR(500)` последний символ не
# словесный, и `\b` после него не срабатывает вовсе.
COLUMN_PATTERN = re.compile(
    r"^\s*(\w+)\s+(VARCHAR\(\d+\)|INTEGER|TIMESTAMP WITH TIME ZONE)(?=[\s,)])",
    re.MULTILINE,
)


def migration() -> ModuleType:
    return load_migration(MIGRATION_PATH)


def declared_table_columns(module: ModuleType) -> dict[str, str]:
    """Колонки `CREATE TABLE`: имя → объявленный тип."""
    declared = {
        match.group(1): match.group(2) for match in COLUMN_PATTERN.finditer(module.CREATE_TABLE_SQL)
    }
    assert declared, "ревизия не объявляет ни одной колонки таблицы реестра"
    return declared


def test_migration_sits_on_top_of_the_previous_head() -> None:
    assert_on_previous_head(migration(), REVISION, PARENT)


def test_revision_tree_has_exactly_one_head() -> None:
    assert_single_head(ALEMBIC_DIR)


def test_it_adds_exactly_the_model_column_to_import_jobs() -> None:
    assert_columns_match_model(migration(), ImportJob, COLUMN_PREFIX)


def test_the_import_jobs_column_type_matches_the_model() -> None:
    columns = model_columns(ImportJob, COLUMN_PREFIX)
    for name, declared in added_columns(migration()).items():
        assert type_matches(columns[name], declared), name


def test_the_column_stays_nullable_and_no_default_is_set() -> None:
    """Backfill нет: у заданий, разобранных до хранилища, файла нет."""
    assert_nullable_without_default(migration(), ImportJob, COLUMN_PREFIX)


def test_downgrade_removes_exactly_what_upgrade_added() -> None:
    assert_downgrade_removes_only_added(migration())


def test_created_table_matches_the_model() -> None:
    """Таблица реестра повторяет модель: имена и типы колонок совпадают."""
    declared = declared_table_columns(migration())

    assert set(declared) == {column.name for column in UploadedFile.__table__.columns}
    for name, column in UploadedFile.__table__.columns.items():
        assert declared[name] == column_type_sql(column), name


def test_created_table_declares_the_model_indexes() -> None:
    """`key` уникален, `uploader_id` индексирован — иначе схема разойдётся с моделью."""
    indexes = " ".join(migration().CREATE_INDEX_SQL)

    assert "ix_uploaded_file_key" in indexes
    assert "ix_uploaded_file_uploader_id" in indexes
    assert "UNIQUE INDEX" in indexes


def test_the_primary_key_is_generated_by_the_database() -> None:
    """Голый `INTEGER` в primary key — это `null value in column "id"` на PostgreSQL.

    SQLAlchemy собирает модель в `SERIAL`, поэтому ручное объявление таблицы
    обязано повторить автоинкремент: `GENERATED BY DEFAULT AS IDENTITY`.
    Юнит-тесты на SQLite этого не ловят — там схема берётся из моделей, а
    ревизия не исполняется. Ошибка всплыла на стенде первым же `INSERT`.
    """
    declaration = " ".join(migration().CREATE_TABLE_SQL.split())

    assert "id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY" in declaration


def test_downgrade_drops_the_table_and_its_indexes() -> None:
    module = migration()
    declared = " ".join(module.DROP_INDEX_SQL)

    assert "ix_uploaded_file_key" in declared
    assert "ix_uploaded_file_uploader_id" in declared
