"""Ревизия `0055_notification_rules`: таблица правил и ссылка из доставки.

DDL ревизии — `CREATE TABLE ... IF NOT EXISTS` и
`ALTER TABLE ... ADD COLUMN IF NOT EXISTS` — юнит-тестом на SQLite целиком не
выполнить: `ADD COLUMN IF NOT EXISTS` понимает PostgreSQL, а не SQLite. Поэтому
проверяются вещи, которые ломаются тихо:

* ревизия стоит на голове дерева (`0054_invoice_file_keys`) и голова одна: вторая
  голова валит `alembic upgrade head` с «Multiple head revisions»;
* объявление таблицы совпадает с моделью `NotificationRule` по именам и типам
  колонок и объявляет те же индексы — расхождение всплывает только на живой базе
  как `UndefinedColumn` и медленный перебор правил;
* `notification_deliveries.rule_id` добавлена nullable и без `DEFAULT` (backfill
  нет) и снимается в `downgrade` — иначе ревизия необратима;
* `id` объявлен `GENERATED BY DEFAULT AS IDENTITY`, а не голым `INTEGER`.

Сам DDL на настоящей PostgreSQL проверяется на стенде: `alembic upgrade head`,
затем `alembic downgrade -1` и снова `alembic upgrade head`.
"""

import re
from pathlib import Path
from types import ModuleType
from typing import Any

import sqlalchemy as sa

from app.models.telegram import NotificationDelivery, NotificationRule
from tests.migration_support import (
    added_columns,
    assert_columns_match_model,
    assert_downgrade_removes_only_added,
    assert_nullable_without_default,
    assert_on_previous_head,
    assert_single_head,
    column_type_sql,
    load_migration,
    model_columns,
    type_matches,
)

ALEMBIC_DIR = Path(__file__).resolve().parents[1] / "alembic"
MIGRATION_PATH = ALEMBIC_DIR / "versions" / "0055_notification_rules.py"
REVISION = "0055_notification_rules"
PARENT = "0054_invoice_file_keys"

# Колонка доставки, которую заводит ревизия: ссылка на правило.
COLUMN_PREFIX = "rule_"

# Объявление колонки в `CREATE TABLE`: имя и тип. Правая граница — пробел,
# запятая или скобка, а не `\b`: у `VARCHAR(120)` последний символ не словесный.
COLUMN_PATTERN = re.compile(
    r"^\s*(\w+)\s+"
    r"(VARCHAR\(\d+\)|INTEGER|BOOLEAN|JSON|TIMESTAMP WITH TIME ZONE)"
    r"(?=[\s,)])",
    re.MULTILINE,
)


def migration() -> ModuleType:
    return load_migration(MIGRATION_PATH)


def declared_table_columns(module: ModuleType) -> dict[str, str]:
    """Колонки `CREATE TABLE`: имя → объявленный тип."""
    declared = {
        match.group(1): match.group(2) for match in COLUMN_PATTERN.finditer(module.CREATE_TABLE_SQL)
    }
    assert declared, "ревизия не объявляет ни одной колонки таблицы правил"
    return declared


def expected_type(column: Any) -> str:
    """Ожидаемый DDL-тип: общий обвязчик знает строки, числа и моменты, не JSON."""
    if isinstance(column.type, sa.Boolean):
        return "BOOLEAN"
    if isinstance(column.type, sa.JSON):
        return "JSON"
    return column_type_sql(column)


def test_migration_sits_on_top_of_the_previous_head() -> None:
    assert_on_previous_head(migration(), REVISION, PARENT)


def test_revision_tree_has_exactly_one_head() -> None:
    assert_single_head(ALEMBIC_DIR)


def test_created_table_matches_the_model() -> None:
    """Таблица правил повторяет модель: имена и типы колонок совпадают."""
    declared = declared_table_columns(migration())

    assert set(declared) == {column.name for column in NotificationRule.__table__.columns}
    for name, column in NotificationRule.__table__.columns.items():
        assert declared[name] == expected_type(column), name


def test_created_table_declares_the_model_indexes() -> None:
    """Индексы модели обязаны быть в DDL: иначе перебор правил идёт без них."""
    indexes = " ".join(migration().CREATE_INDEX_SQL)

    assert "ix_notification_rules_user_id" in indexes
    assert "ix_notification_rules_dormitory_id" in indexes
    assert "ix_notification_rules_dormitory_table" in indexes
    assert "ix_notification_deliveries_rule_id" in indexes


def test_the_primary_key_is_generated_by_the_database() -> None:
    """Голый `INTEGER` в primary key — это `null value in column "id"` в PostgreSQL."""
    declaration = " ".join(migration().CREATE_TABLE_SQL.split())

    assert "id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY" in declaration


def test_the_delivery_gets_exactly_the_rule_column() -> None:
    assert_columns_match_model(migration(), NotificationDelivery, COLUMN_PREFIX)


def test_the_rule_column_type_matches_the_model() -> None:
    columns = model_columns(NotificationDelivery, COLUMN_PREFIX)
    for name, declared in added_columns(migration()).items():
        assert type_matches(columns[name], declared), name


def test_the_rule_column_stays_nullable_and_no_default_is_set() -> None:
    """Backfill нет: у прежних доставок правила не было, `NULL` — верное состояние."""
    assert_nullable_without_default(migration(), NotificationDelivery, COLUMN_PREFIX)


def test_downgrade_removes_exactly_what_upgrade_added() -> None:
    assert_downgrade_removes_only_added(migration())


def test_downgrade_drops_the_table_and_its_indexes() -> None:
    module = migration()
    dropped = " ".join(module.DROP_INDEX_SQL)

    for name in (
        "ix_notification_deliveries_rule_id",
        "ix_notification_rules_dormitory_table",
        "ix_notification_rules_dormitory_id",
        "ix_notification_rules_user_id",
    ):
        assert name in dropped
    source = Path(MIGRATION_PATH).read_text(encoding="utf-8")
    assert "DROP TABLE IF EXISTS notification_rules" in source
