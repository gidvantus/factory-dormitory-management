"""Экранирование `LIKE`: значение от клиента — это текст, а не шаблон.

Поиск в платформенном контуре ищет подстроку (`%…%`) сразу по нескольким
текстовым колонкам: `app/api/platform_users.py` — по email и ФИО,
`app/api/platform_invoices.py` — по названию и ИНН организации. Без
экранирования `search=%` вернул бы всю платформу, а `search=_` — любую строку
длины больше нуля: `LIKE` толкует значение как шаблон.

Шаблон собирается **в одном месте** намеренно: вторая копия экранирования
разошлась бы с первой, и одна из поисковых ручек начала бы отвечать иначе на
тот же запрос.
"""

# Символ экранирования для `LIKE`. Обратный слэш выбран потому, что он не
# встречается ни в email и ФИО, ни в названиях организаций и ИНН.
ESCAPE_CHARACTER = "\\"


def like_pattern(value: str) -> str:
    """Подстрока как шаблон `LIKE`: `%`, `_` и обратный слэш экранируются.

    Второй `escape=` передаётся в сам запрос (`Column.ilike(..., escape=...)`):
    одной подстановки обратного слэша мало, `LIKE` должен знать, чем именно
    экранировано.
    """
    escaped = value.replace(ESCAPE_CHARACTER, ESCAPE_CHARACTER * 2)
    for char in ("%", "_"):
        escaped = escaped.replace(char, ESCAPE_CHARACTER + char)
    return f"%{escaped}%"
