"""Снимок редакции публичного документа: одно правило для всех, кто его пишет.

Документы сервиса (согласие на обработку персональных данных, правила
использования, оферта) лежат в таблице `documents`, и факт принятия каждого
хранится снимком: код документа и `documents.updated_at` на момент нажатия. Снимок
пишут три потребителя — `app/consent.py` (`users.consent_*`), там же правила
(`users.terms_*`), и `app/offer.py` (`invoices.offer_*`).

Правило «чего стоит отсутствующая строка документа» поэтому живёт здесь одно на
всех: помощник возвращает `NULL`, а не падает. Принятие важнее справочника —
запрос регистрации, активации или покупки не должен рушиться из-за пустой таблицы
документов. Держать это правило в двух местах нельзя: поменяв его в одном,
получишь разные снимки у пользователя и у счёта.

Разные потребители пишут в разные таблицы и в разные колонки, поэтому здесь
только чтение: кто и когда принял — это по-прежнему дело `consent.py` и
`offer.py`.
"""

from datetime import datetime

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models.document import Document


def document_revision(db: Session, code: str) -> datetime | None:
    """Редакция документа `code` — `documents.updated_at` или `NULL`.

    Отсутствующая строка документа не ошибка: снимок остаётся пустым, а запрос,
    который его пишет, проходит. Устроено так у всех потребителей сразу — чтобы
    согласие, правила и акцепт оферты отвечали на вопрос «на какую редакцию
    согласились» одинаково.
    """
    return db.scalar(select(Document.updated_at).where(Document.code == code))
