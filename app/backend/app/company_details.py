"""Чтение реквизитов поставщика для печатных форм.

Модуль ровно об одном: отдать единственную строку `company_details` или `None`.
Он ничего не создаёт и не пишет — засев делает миграция `0067_company_details`,
а правила правки живут в платформенном роутере (`app/api/platform_company.py`).
Второй экземпляр этих правил здесь разошёлся бы с оригиналом на первой же правке.

`None` — нормальный ответ: в тестах схема собирается из моделей без миграций, и
строки там нет вовсе. Печатная форма в этом случае печатает заглушку поставщика
(`app/billing_forms.py`), а не выдуманные реквизиты.

Модуль не знает про HTTP и не импортирует роутеры: им пользуются и сборка PDF
(`app/invoice_files.py`), и платформенные ручки — каждый по-своему.
"""

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models.company_details import SINGLE_ROW_ID, CompanyDetails


def load(db: Session) -> CompanyDetails | None:
    """Реквизиты поставщика: единственная строка или `None`, если её нет.

    Чтения по `id = 1`, а не «первая строка»: строку одну держит
    `CHECK (id = 1)`, и запрос не должен зависеть от того, что вернёт `LIMIT 1`
    на испорченной базе.

    Сессия остаётся в том же состоянии, в каком пришла: `load` не коммитит, не
    делает `flush` и не создаёт строку.
    """
    return db.scalar(select(CompanyDetails).where(CompanyDetails.id == SINGLE_ROW_ID))
