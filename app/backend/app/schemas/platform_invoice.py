"""Счета платформы: строка и страница для кабинета оператора.

Контур тот же, что у организаций (`app/schemas/platform_organization.py`) и
пользователей (`app/schemas/platform_user.py`): ручки открывает сервисный токен
кабинета оператора (`X-Operator-Token`), а не cookie основного кабинета.

**Строка счёта не переписана заново, а дополнена.** `PlatformInvoice`
наследует `InvoiceResponse` — тот же ответ, что получает кабинет клиента, — и
добавляет к нему два поля: организацию, которой счёт выставлен. Так поля счёта
(`status_label`, `amount_label`, снимок покупателя и предмета) остаются одним
контрактом на оба кабинета: правка представления счёта в одном месте сразу
видна в обоих, а расхождения «в кабинете оператора поле есть, в кабинете клиента
нет» не появляется.

`can_manage` в платформенном контуре всегда `true`: право здесь даёт сервисный
токен, ролей организации в этом контуре нет, и второго правила ролей рядом с
`EDIT_ROLES` (`app/api/organization.py`) экран держать не должен.
"""

from pydantic import BaseModel, Field

from app.schemas.invoice import InvoiceResponse


class PlatformInvoice(InvoiceResponse):
    """Строка реестра счетов платформы: счёт клиента плюс его организация.

    `organization_id` и `organization_name` берутся из строки организации, а не
    из снимка покупателя: снимок (`buyer_name`) — то, что попало в счёт при
    покупке, а карточка организации показывает, как она называется сейчас.
    Название бывает `null` у пустой заготовки организации.
    """

    organization_id: int
    organization_name: str | None


class PlatformInvoicePage(BaseModel):
    """Страница списка: элементы и общее число счетов по тем же условиям.

    `total` считается отдельным запросом и не зависит от `limit`/`offset`: по
    нему фронт понимает, есть ли ещё страница, — пока `len(items) < total`,
    «Показать ещё» видна.
    """

    items: list[PlatformInvoice]
    total: int = Field(examples=[12])
