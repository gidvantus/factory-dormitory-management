"""Правила уведомлений: таблица `notification_rules` и ссылка из доставки.

Персональный конструктор правил (issue #109): правило принадлежит пользователю,
привязано к общежитию и таблице и срабатывает при записи строки, когда
выполнены условия по столбцам. Ревизия аддитивная:

* новая таблица `notification_rules` — пока в ней нет строк, она ни на что не
  влияет;
* `notification_deliveries.rule_id` — nullable-колонка без `server_default`, с
  `ON DELETE SET NULL`: история доставок переживает удаление правила, а прежние
  строки остаются с `NULL` («доставка не от правила»). Колонок с полями
  сообщения здесь нет намеренно: сообщение — это название правила.

**Номер ревизии** взят по фактической голове (`alembic heads` →
`0054_invoice_file_keys`), а не по номеру из плана: две ревизии от одной головы
дают две головы и ломают `alembic upgrade head` — этот случай в репозитории уже
был (см. докстринг `0032_telegram_notifications`).

**Идемпотентность.** `upgrade` защищён `IF NOT EXISTS` и переживает повторный
запуск после обрыва.

**Обратимость.** `downgrade` снимает колонку, индексы и таблицу. Данные
пользователей он не затрагивает; теряется только сам конструктор, а `rule_id` у
уже отправленных доставок — ссылка, а не сообщение: тексты остаются в `title`.

Идентификатор ревизии короче 32 символов: колонка `alembic_version.version_num`
имеет тип `varchar(32)`.
"""

from collections.abc import Sequence

import sqlalchemy as sa
from alembic import op

revision: str = "0055_notification_rules"
down_revision: str | None = "0054_invoice_file_keys"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

# Таблица правил: колонки и типы совпадают с моделью `NotificationRule`.
# `id` — `GENERATED BY DEFAULT AS IDENTITY`, как в `0053_uploaded_files`: без
# identity вставка на PostgreSQL падала бы с `null value in column "id"`.
# Потолок в 80 символов у `name` держит домен, а длина колонки — 120: отказ
# должен быть текстом контракта, а не ошибкой базы.
CREATE_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS notification_rules (
    id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id INTEGER NOT NULL,
    dormitory_id INTEGER NOT NULL,
    table_key VARCHAR(32) NOT NULL,
    name VARCHAR(120) NOT NULL,
    is_enabled BOOLEAN DEFAULT true NOT NULL,
    conditions JSON DEFAULT '[]' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY(user_id) REFERENCES users (id) ON DELETE CASCADE,
    FOREIGN KEY(dormitory_id) REFERENCES dormitories (id) ON DELETE CASCADE
)
"""

# Ссылка доставки на правило. `DEFAULT` нет и backfill не делается: у прежних
# доставок правила нет, и `NULL` — правильное состояние.
ADD_COLUMNS_SQL = (
    "ALTER TABLE notification_deliveries ADD COLUMN IF NOT EXISTS rule_id INTEGER "
    "REFERENCES notification_rules (id) ON DELETE SET NULL",
)

DROP_COLUMNS_SQL = ("ALTER TABLE notification_deliveries DROP COLUMN IF EXISTS rule_id",)

# Имена индексов — те, которые SQLAlchemy выводит из модели. Составной индекс по
# паре из хука записи (общежитие, таблица) — главный: по нему перебираются
# правила на каждую правку ячейки.
CREATE_INDEX_SQL = (
    "CREATE INDEX IF NOT EXISTS ix_notification_rules_user_id ON notification_rules (user_id)",
    "CREATE INDEX IF NOT EXISTS ix_notification_rules_dormitory_id "
    "ON notification_rules (dormitory_id)",
    "CREATE INDEX IF NOT EXISTS ix_notification_rules_dormitory_table "
    "ON notification_rules (dormitory_id, table_key)",
    "CREATE INDEX IF NOT EXISTS ix_notification_deliveries_rule_id "
    "ON notification_deliveries (rule_id)",
)

DROP_INDEX_SQL = (
    "DROP INDEX IF EXISTS ix_notification_deliveries_rule_id",
    "DROP INDEX IF EXISTS ix_notification_rules_dormitory_table",
    "DROP INDEX IF EXISTS ix_notification_rules_dormitory_id",
    "DROP INDEX IF EXISTS ix_notification_rules_user_id",
)


def upgrade() -> None:
    op.execute(sa.text(CREATE_TABLE_SQL))
    # Колонка добавляется **до** индексов: индекс по `rule_id` иначе падает с
    # `column "rule_id" does not exist`. Ошибка была поймана на стенде, а не в
    # юнит-тестах: SQLite собирает схему из моделей и DDL ревизии не исполняет.
    for statement in ADD_COLUMNS_SQL:
        op.execute(sa.text(statement))
    for statement in CREATE_INDEX_SQL:
        op.execute(sa.text(statement))


def downgrade() -> None:
    # Порядок обратный: сначала снимаем ссылку на правило, потом само правило —
    # иначе внешний ключ не даст удалить таблицу.
    for statement in DROP_COLUMNS_SQL:
        op.execute(sa.text(statement))
    for statement in DROP_INDEX_SQL:
        op.execute(sa.text(statement))
    op.execute(sa.text("DROP TABLE IF EXISTS notification_rules"))
