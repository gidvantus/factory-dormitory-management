# Таблица реестра: колонки и типы совпадают с моделью `UploadedFile`.
# `id` — `GENERATED BY DEFAULT AS IDENTITY`, а не голый `INTEGER`: модель
# объявляет его первичным ключом с автоинкрементом (SQLAlchemy отдаёт для него
# `SERIAL`), и без identity в базе вставка падала бы с
# `null value in column "id"`. На SQLite юнит-тестов это не видно — там схема
# собирается из моделей, поэтому проверяется на стенде.
CREATE_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS uploaded_file (
    id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    key VARCHAR(500) NOT NULL,
    uploader_kind VARCHAR(16),
    uploader_id INTEGER,
    purpose VARCHAR(32),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    PRIMARY KEY (id)
)
"""

# Колонка задания импорта: ключ хранилища в том виде, в каком его принимает
