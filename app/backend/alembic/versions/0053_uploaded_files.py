"""Реестр загруженных файлов: таблица `uploaded_file` и `import_jobs.file_key`.

Задача подключает файловое хранилище (`app/storage.py`) к импорту «Размещение
персонала»: файл `.xlsx`, который разбирает ручка импорта, теперь сохраняется, а
ссылка на него отдаётся фронту полем `file_url`. Ревизия заводит две части схемы:

* таблицу `uploaded_file` — реестр загрузок (`app/models/uploaded_file.py`). Учёт,
  а не право: `key` уникален, `uploader_kind` / `uploader_id` / `purpose`
  заполняются при загрузке;
* колонку `import_jobs.file_key` — ключ хранилища в том же виде, в каком его
  принимает `app.storage.read_bytes` (`2026-10-29/<uuid>.xlsx`, без префикса
  `uploads/`). Именно по ней `app/file_access.can_read` находит общежитие и его
  организацию, поэтому доступ решает принадлежность данных, а не факт загрузки.

**Backfill не делается.** У уже существующих заданий импорта файла нет: он не
сохранялся вовсе, и `file_key IS NULL` — честное «файла нет». Выдумывать ключ
для них нечем, а копировать неоткуда: строки `import_jobs` не чистятся и не
переносятся этой ревизией.

**Идемпотентность.** `upgrade` защищён `IF NOT EXISTS` и переживает повторный
запуск после обрыва. Автогенерация не используется: ревизия состоит из DDL,
которое PostgreSQL делает без пересборки таблицы.

**Обратимость.** `downgrade` снимает колонку и таблицу. Потеря — ключи файлов у
заданий импорта и сам реестр загрузок; файлы в бакете при этом остаются, но
перестают быть доступными (ссылок на них больше нет). Это принято для отката
схемы; объектов в S3 откат не трогает.

Идентификатор ревизии короче 32 символов: колонка `alembic_version.version_num`
имеет тип `varchar(32)`.
"""

