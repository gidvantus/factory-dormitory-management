"""Журнал действий: колонка `actor_name` — ФИО автора снимком на момент записи.

Задача, в которой родилась ревизия, называла её `0043_audit_actor_name` с
`down_revision = "0042_merge_develop_s"`. К моменту работы голова дерева ушла
вперёд: поверх `0042_merge_develop_s` уже лежит `0043_dormitories_organization`
(#77), поэтому здесь `0044_audit_actor_name` с
`down_revision = "0043_dormitories_organization"`. Вторая голова в дереве
недопустима.

**Зачем снимок, а не join.** В строке журнала автор хранится идентификатором
(`actor_id`), и внешнего ключа на `users` нет намеренно: журнал обязан переживать
удаление пользователя и не уносить строки за ним. Join на `users` при чтении дал
бы **текущее** имя: смена фамилии переписала бы историю задним числом, а для
журнала это ложь — он показывает того, кто действовал, а не того, как человек
зовётся сейчас. Поэтому ФИО кладётся в саму строку в момент записи.

**Что делает ревизия.** Одна колонка `actor_name VARCHAR(255)` на
партиционированной таблице `audit_events`. У партиционированной таблицы
`ADD COLUMN` — операция уровня метаданных: колонка наследуется всеми
существующими партициями, данные не переписываются, блокировки строк нет.
Отдельного `ALTER` на каждую партицию не нужно.

`DEFAULT` не задаётся и backfill не делается: у строк, записанных до этой
ревизии, значение остаётся `NULL`. Заполнить их можно было бы только тем же join
на `users`, то есть текущими именами — ровно той ложью, от которой уходим.
Клиент показывает такие строки как «Сотрудник №<actor_id>».

Длина 255 совпадает с `users.full_name`: имя, которое не влезло в свою колонку,
обрезать в журнале нельзя — это была бы уже не копия.

Автогенерация здесь не используется: alembic не знает про партиции и, увидев
расхождение модели и прод-схемы, предложил бы пересоздать таблицу — этого делать
нельзя, иначе пропадут партиции и весь журнал. `upgrade()` идемпотентен
(`IF NOT EXISTS`): повторный запуск после обрыва не падает.

**Необратимое.** `downgrade` снимает колонку вместе со всеми записанными именами:
другого места у снимка нет, и восстановить его можно только повторной записью
новых действий. Это осознанно: колонка необязательная, а старый код с ней
работает (она nullable).
"""

from collections.abc import Sequence

import sqlalchemy as sa
from alembic import op

revision: str = "0044_audit_actor_name"
down_revision: str | None = "0043_dormitories_organization"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

SCHEMA = "public"
TABLE = "audit_events"
COLUMN = "actor_name"
TYPE = "VARCHAR(255)"

ADD_COLUMN_SQL = f"ALTER TABLE {SCHEMA}.{TABLE} ADD COLUMN IF NOT EXISTS {COLUMN} {TYPE}"

DROP_COLUMN_SQL = f"ALTER TABLE {SCHEMA}.{TABLE} DROP COLUMN IF EXISTS {COLUMN}"


def upgrade() -> None:
    # Колонка наследуется всеми партициями: отдельного `ALTER` на каждую не нужно.
    # `DEFAULT` не задаётся — у прежних строк остаётся `NULL`, и это честно
    # означает «имя автора не записано».
    op.execute(sa.text(ADD_COLUMN_SQL))


def downgrade() -> None:
    # `DROP COLUMN` на партиционированной таблице так же снимает колонку со всех
    # партиций. Данные снимка при этом теряются — другого места у них нет.
    op.execute(sa.text(DROP_COLUMN_SQL))
