# Таблица описана только теми колонками, которые ревизия пишет. Заголовков
# документа и его порядка здесь нет намеренно: `UPDATE` их не упоминает, и
# случайная правка не должна оказаться в запросе.
DOCUMENTS = sa.table(
    "documents",
    sa.column("code", sa.String(length=50)),
    sa.column("body", sa.Text()),
    sa.column("updated_at", sa.DateTime(timezone=True)),
)


def _rewrite(bodies: dict[str, str]) -> None:
    """Записать тексты трёх документов и сдвинуть их редакцию.

    Один `UPDATE` на код: текст и `updated_at = now()` меняются вместе, иначе
    редакция разошлась бы с текстом. Строка, которой в таблице нет, остаётся
    отсутствующей — `UPDATE` её не создаёт.
    """
    connection = op.get_bind()
    for code in CODES:
        connection.execute(
            DOCUMENTS.update()
            .where(DOCUMENTS.c.code == code)
            .values(body=bodies[code], updated_at=sa.func.now())
        )


def upgrade() -> None:
    """Новые тексты политики, правил и согласия; оферта не затрагивается."""
    _rewrite(NEW_BODIES)


def downgrade() -> None:
    """Прежние тексты трёх документов и новая отметка редакции: откат — тоже правка."""
    _rewrite(OLD_BODIES)
