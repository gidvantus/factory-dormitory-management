#!/bin/sh
# Старт api: проверка дерева миграций, миграции, сервер.
# Готовность базы гарантирует healthcheck сервиса db в docker-compose.yml.
set -e

# Ровно одна голова миграций. Две головы означают, что ветки ревизий разошлись:
# `alembic upgrade head` в таком дереве падает с «Multiple head revisions»,
# api уходит в цикл перезапуска (restart: unless-stopped), а nginx фронта отдаёт
# 502 на /api/. Проверка стоит ДО миграций, чтобы в логах контейнера была
# причина, а не только трассировка alembic: так это и случилось 5 ноября.
# Дерево только читается, схема не меняется.
HEADS="$(alembic heads 2>&1)" || {
  echo "ОШИБКА: не удалось прочитать дерево миграций:" >&2
  printf '%s\n' "$HEADS" >&2
  exit 1
}
# grep -c печатает 0 и выходит с кодом 1, когда совпадений нет: без `|| true`
# `set -e` уронил бы скрипт на пустом списке голов вместо нашей проверки.
HEAD_COUNT="$(printf '%s\n' "$HEADS" | grep -c '(head)' || true)"
if [ "$HEAD_COUNT" != "1" ]; then
  echo "ОШИБКА: в дереве миграций $HEAD_COUNT головы, нужна ровно одна — ветки ревизий разошлись. api не стартует, чтобы не работать на неполной схеме." >&2
  printf '%s\n' "$HEADS" >&2
  echo "Починка: python _tools/alembic-heads.py --merge, коммит созданной ревизии, деплой — docs/deploy.md, «Если основной домен отвечает 502 на /api/health»." >&2
  exit 1
fi

echo "Применяю миграции базы данных..."
alembic upgrade head

echo "Запускаю api на порту 8000..."
exec uvicorn app.main:app --host 0.0.0.0 --port 8000
