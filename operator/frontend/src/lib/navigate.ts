/**
 * Переход по абсолютному адресу другого origin.
 *
 * Ссылку входа под пользователем собирает основной API: адрес сайта знает
 * только он, а кабинет получает строку готовой и отдаёт её браузеру целиком.
 * `fetch` здесь не годится — сессию ставит `Set-Cookie` обычного перехода на
 * origin сайта, а не ответ ручки кабинета.
 *
 * Отдельная функция — ради проверяемости: `window.location` в jsdom
 * неизменяем, а экран должен остаться покрытым тестом на переход.
 */
export function openLink(url: string): void {
  window.location.assign(url);
}
